def display_title(commons_title: str) -> str:
    """'File:100 metres hurdles.webm' -> '100 metres hurdles'."""
    title = commons_title[5:] if commons_title.startswith("File:") else commons_title
    return re.sub(r"\.(webm|ogv|mp4|mkv)$", "", title, flags=re.IGNORECASE)


def _seconds(value: float) -> str:
    return f"{value:g} s"


def render_credits(clips: list[dict]) -> str:
    """CREDITS.md for the shipped stock excerpts.

    Each clip is {"out", "source": {title, page, artist, license, license_url, start, seconds},
    "changes"}, the shape of a stock entry in media-manifest.json."""
    lines = [
        f"# Suite Demo Kit {KIT_VERSION}: credits",
        "",
        "This file is generated by `python demo-kit/build-kit.py credits` from the stock list the media",
        "were cut from; do not edit it by hand.",
        "",
        "## Licences in the kit",
        "",
        "- The scene collection, the Stream Deck profiles, the setup card and the scripts that build them:",
        f"  {CODE_LICENSE}, like the repository they come from.",
        f"- The media we made (listed below): {OUR_LICENSE}, {OUR_LICENSE_URL}, by {OUR_AUTHOR}.",
        "- The stock excerpts: each under its own Creative Commons licence, below.",
        "",
        "## Stock excerpts",
        "",
        "From Wikimedia Commons. Each file in the kit is a changed excerpt of the original, not the",
        "original itself.",
    ]
    for clip in clips:
        s = clip["source"]
        end = s["start"] + s["seconds"]
        lines += [
            "",
            f"### media/{clip['out']}",
            "",
            f"- Title: “{display_title(s['title'])}” (Commons file `{s['title']}`)",
            f"- Author: {s['artist']}",
            f"- Licence: {s['license']}, {s['license_url']}",
            f"- Source page: {s['page']}",
            f"- Part used: {_seconds(s['start'])} to {_seconds(end)} of the original",
            f"- Changes: {clip['changes']}",
        ]
    lines += [
        "",
        "## Media we made",
        "",
        f"By {OUR_AUTHOR}, {OUR_LICENSE}, {OUR_LICENSE_URL}. Made for this kit by `build-kit.py`;",
        "no footage, sound or image of anyone else is in them. The title image is drawn with",
        "Windows' Segoe UI; no font file is in the kit.",
        "",
        "| File | What it is |",
        "|---|---|",
        *[f"| `{name}` | {what} |" for name, what in ORIGINALS],
        "",
        "## Played from YouTube, not included",
        "",
        "The setup card suggests this video for the Speed Page. The kit holds no file of it; YouTube's",
        "own player plays it, unchanged.",
        "",
        f"- Title: “{YOUTUBE_CREDIT['title']}”, {YOUTUBE_CREDIT['watch']}",
        f"- Author: {YOUTUBE_CREDIT['artist']}, {YOUTUBE_CREDIT['page']}",
        f"- Licence: {YOUTUBE_CREDIT['license']}, {YOUTUBE_CREDIT['license_url']}",
        "",
    ]
    return "\n".join(lines)


def credits_problems(text: str, clips: list[dict]) -> list[str]:
    """What CREDITS.md lacks for the shipped clips (plan section 12, the licence row)."""
    problems = []
    for clip in clips:
        s = clip["source"]
        need = {"file": f"media/{clip['out']}", "title": display_title(s["title"]), "author": s["artist"],
                "licence": f"Licence: {s['license']}, {s['license_url']}", "page": s["page"],
                "changes": clip["changes"]}
        section = _section(text, f"### media/{clip['out']}")
        if section is None:
            problems.append(f"{clip['out']}: no section in CREDITS.md")
            continue
        for what, value in need.items():
            if value not in section:
                problems.append(f"{clip['out']}: CREDITS.md does not give its {what} ({value})")
    return problems


def parse_credits(text: str) -> list[dict]:
    """The stock sections of a CREDITS.md, read back into the clip shape render_credits() takes.

    The tests use it where stock-credits.json is not on the machine: render_credits() of what
    it reads must give the same file, and the clip table and the on-screen credits must match it."""
    clips = []
    for block in text.split("\n### media/")[1:]:
        lines = block.split("\n")
        fields = {}
        for line in lines[1:]:
            if line.startswith("#"):
                break
            if line.startswith("- ") and ": " in line:
                key, value = line[2:].split(": ", 1)
                fields[key] = value
        commons = re.search(r"\(Commons file `([^`]+)`\)$", fields.get("Title", ""))
        licence, _, licence_url = fields.get("Licence", "").partition(", ")
        part = re.fullmatch(r"([\d.]+) s to ([\d.]+) s of the original", fields.get("Part used", ""))
        if not (commons and licence_url and part):
            raise ValueError(f"CREDITS.md: the section for media/{lines[0]} is not in render_credits' form")
        start, end = float(part.group(1)), float(part.group(2))
        clips.append({"out": lines[0], "changes": fields.get("Changes", ""),
                      "source": {"title": commons.group(1), "page": fields.get("Source page", ""),
                                 "artist": fields.get("Author", ""), "license": licence,
                                 "license_url": licence_url, "start": start, "seconds": round(end - start, 3)}})
    return clips


def _section(text: str, heading: str) -> str | None:
    start = text.find(heading + "\n")
    if start < 0:
        return None
    end = text.find("\n#", start + len(heading))
    return text[start:] if end < 0 else text[start:end]


def on_screen_problems(line: str, clips: list[dict]) -> list[str]:
    """What the on-screen Kit Credits text lacks: each shipped clip's title, author and licence."""
    problems = []
    for clip in clips:
        s = clip["source"]
        entry = f"“{display_title(s['title'])}” by {s['artist']}, {s['license']}"
        if entry not in line:
            problems.append(f"{clip['out']}: the on-screen credits do not say {entry}")
    return problems


# Anything that would load from outside the card, or run.
_EXTERNAL = re.compile(r"<script|<link|<iframe|<img|@import|url\(|\bsrc\s*=|\bhref\s*=", re.IGNORECASE)


def setup_card_problems(html: str) -> list[str]:
    """What keeps the setup card from being the static local page the Speed Page shows."""
    problems = []
    if not html.startswith("<!doctype html>"):
        problems.append("the card does not start with <!doctype html>")
    if '<meta charset="utf-8">' not in html:
        problems.append("the card does not declare UTF-8")
    for match in _EXTERNAL.finditer(html):
        problems.append(f"the card loads or runs something: {match.group(0)!r}")
    if "width: 1280px; height: 720px" not in html:
        problems.append("the card is not laid out at the Speed Page's 1280x720")
    for words in ("Keep the link on", "Copy address", "Local file", "Speed Page", YOUTUBE_ID, "0.25x to 2x",
                  "refresh the source", "OBS page key", "Blender Foundation, CC BY 3.0"):
        if words not in html:
            problems.append(f"the card does not say {words!r}")
    if len(html.encode("utf-8")) > 6000:
        problems.append("the card is over 6000 bytes")
    return problems


