"""Suite Demo Kit: CREDITS.md and the checks on the kit's texts (plan step 3). Standard library only.

CREDITS.md is generated, never edited by hand: `build-kit.py credits` reads the stock rows
from stock-credits.json (after the same size and SHA-1 check as the media step) and writes
it with render_credits(). Each stock excerpt gets its title, author, licence with the
licence URL, the Commons page, the part of the original that was cut and the changes made
(CC BY's indicate-changes rule); our own media and the YouTube video the setup card
suggests follow.

credits_problems() and on_screen_problems() are the plan's risk-row checks (section 12):
every shipped clip's page and licence URL are in CREDITS.md, and every shipped clip has a
line in the on-screen Kit Credits text. setup_card_problems() keeps the setup card (D-3)
what the Speed Page needs: a static local page, no script, nothing loaded from anywhere.
"""
